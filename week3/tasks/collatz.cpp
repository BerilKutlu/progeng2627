/** Collatz conjecture¶

Wikipedia describes the Collatz conjecture as follows:

Take any natural number n. If n is even, divide it by 2 to get n/2. If n is odd, multiply 
it by 3 and add 1 to obtain 3n + 1. Repeat the process (which has been called "Half Or Triple Plus One", or HOTPO) 
indefinitely. The conjecture is that no matter what number you start with, you shall always eventually reach 1.
See also this alternative formulation.
Sequence¶
Write a program which reads a (natural) number from the user and prints the corresponding sequence 
of numbers generated by the Collatz conjecture algorithm, ending with 1. For example if the starting 
number is 3, the sequence is 10 5 16 8 4 2 1.
Number of steps¶
Extend the program above by printing after the sequence also the number of steps required to reach 1 . 
For example if the starting number is 3, then 1 is reached in 7 steps.
Maximum number 
Extend the program further so that also the maximum number generated in the process is identified 
(and printed after the full sequence and number of steps). For example if the starting number is 3, 
then, as we saw above, 1 is reached in 7 steps and the maximum number generated in the process is 16. */
#include <iostream>

int main(){
    int n;
    std::cin >> n;
    int temp = n;
    std::cout << temp << " ";
    int i = 0;
    int max = temp;
    while(temp != 1){
        if(temp % 2 == 0){
            i++;
            temp = temp / 2;
        } else{
            i++;
            temp = temp * 3;
            temp++;
        }
        if(temp > max) {
            max = temp;
        }
        std::cout << temp << " ";
    }
    std::cout << std::endl;
    std::cout << "the number of steps to reach 1: " << i << std::endl; 
    std::cout << "the maximum number that is reached is: " << max << std::endl;
}